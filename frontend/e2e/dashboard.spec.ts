test('browser never receives server-side credentials and rejects unauthenticated artifacts',async({request})=>{
 for(const path of ['/api/v1/runs','/api/v1/models','/api/v1/batches','/api/v1/runs/unknown/patch'])expect((await request.get(path)).status()).toBe(401)
 const response=await request.get('/');expect(response.headers()['content-security-policy']).toContain("frame-ancestors 'none'")
 const html=await response.text();expect(html).not.toContain('SWE_ADMIN_TOKEN');expect(html).not.toContain('GATEWAY_API_KEY')
})

test('browser creates a real bounded local batch and observes persisted completion',async({page,request})=>{
 await page.goto('/')
 await page.getByLabel('控制台密码').fill('phase2-browser-only-password')
 await page.getByRole('button',{name:'安全登录 →'}).click()
 await expect(page.getByText('让代码执行，验证模型能力。')).toBeVisible()
 await page.locator('aside').getByRole('button',{name:/批量实验/}).click()
 await page.getByText('＋ 新建批量实验').click()
 await page.getByPlaceholder('例如：十月编码能力对比').fill('Browser-created local experiment')
 await page.getByLabel('intervals-001 · v1.0.0').check()
 await page.getByLabel('stub-good / stub-good').check()
 const response=page.waitForResponse(r=>r.url().endsWith('/api/v1/batches')&&r.request().method()==='POST')
 await page.getByRole('button',{name:'确认创建实验'}).click()
 const created=await response;expect(created.status()).toBe(202)
 const batch=await created.json();expect(batch.total).toBe(1)
 await expect.poll(async()=>{const r=await page.request.get('/api/v1/batches/'+batch.id);return (await r.json()).terminal},{timeout:20000}).toBe(1)
 await expect(page.getByText('已完成',{exact:true}).first()).toBeVisible({timeout:10000})
 const exported=await page.request.get('/api/v1/comparison/export?format=json&batch_id='+batch.id)
 expect(exported.status()).toBe(200);expect(await exported.text()).not.toContain('api_key')
})
